/// The spell list [c] casts from: the class's own, or the Wizard list for an
/// Eldritch Knight (Fighter 3+). Null while the class isn't supported yet.
String? spellListIdFor(Character c) {
  final classId = c.characterClass.id;
  if (classId == 'fighter') {
    final ek =
        c.classSelections['fighter_subclass']?.contains('eldritch_knight') ??
        false;
    return ek && c.level >= 3 ? 'wizard' : null;
  }
  // The Wizard class itself isn't implemented yet (only its list).
  if (classId == 'wizard') return null;
  return classSpellLists.containsKey(classId) ? classId : null;
}

bool hasSpellcastingSupport(Character c) => spellListIdFor(c) != null;
